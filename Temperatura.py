with open('DosTemperaturas_24h.csv') as f:
         datos_leidos = f.read()

lista_de_cadenas = datos_leidos.split('\n')
lista_de_cadenas_1 = lista_de_cadenas[0].split(',')
lista_de_cadenas_2 = lista_de_cadenas[1].split(',')

nueva_lista_1= []
nueva_lista_1
for i in range (len(lista_de_cadenas_1)):
    nueva_lista_1.append(int(lista_de_cadenas_1[i]))
nueva_lista_2= []
nueva_lista_2
for i in range (len(lista_de_cadenas_2)):
  nueva_lista_2.append(int(lista_de_cadenas_2[i]))

[x1, y1] = [236, 25]
[x2, y2] = [28, 12]

def ADC2gradosC(valor_ADC):
  valor_grdosC = (y2-y1)/(x2-x1)*(valor_ADC-x1)+y1
  return valor_grdosC

lista_en_gradosC_1= []
lista_en_gradosC_2= []
for valor_ADC in nueva_lista_1:
  valor_grdosC = ADC2gradosC(valor_ADC)
  lista_en_gradosC_1.append(valor_grdosC)

for valor_ADC in nueva_lista_2:
  valor_grdosC = ADC2gradosC(valor_ADC)
  lista_en_gradosC_2.append(valor_grdosC)
import matplotlib.pyplot as plt
n = len(lista_en_gradosC_1)
x= list(range(1, n + 1))
plt.plot(x, lista_en_gradosC_1, label='Temperatura 1')
plt.plot(x, lista_en_gradosC_2, label='Temperatura 2')

# Personalizar la gráfica
plt.xlabel('Eje X')
plt.ylabel('Eje Y')
plt.title('Temperatura')
plt.legend()

# Mostrar la gráfica
plt.show()